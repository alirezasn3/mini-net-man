// NewID returns a short random id for a config item.
func NewID() string {
	b := make([]byte, 4)
	_, _ = rand.Read(b)
	return hex.EncodeToString(b)
}

// Desired is everything the kernel should look like, after the optional
// client-routing feature has been expanded into plain items.
type Desired struct {
	Addresses []model.Address
	Routes    []model.Route
	Rules     []model.Rule
	Firewall  model.Firewall
}

const (
	defaultTableBase    = 200
	defaultPriorityBase = 10000
)

// AllocateExits makes sure every output interface used by an enabled client
// has a stable routing table in cfg.ClientRouting.Exits.
func AllocateExits(cfg *model.Config) {
	cr := &cfg.ClientRouting
	if cr.TableBase == 0 {
		cr.TableBase = defaultTableBase
	}
	if cr.PriorityBase == 0 {
		cr.PriorityBase = defaultPriorityBase
	}
	used := map[int]bool{}
	have := map[string]bool{}
	for _, e := range cr.Exits {
		used[e.Table] = true
		have[e.Interface] = true
	}
	for _, c := range cr.Clients {
		if have[c.Out] {
			continue
		}
		t := cr.TableBase
		for used[t] || t == model.TableDefault || t == model.TableMain || t == model.TableLocal {
			t++
		}
		used[t], have[c.Out] = true, true
		cr.Exits = append(cr.Exits, model.Exit{Interface: c.Out, Table: t})
	}
}

// Expand merges manual items with the ones generated by client routing.
// ifaceNets returns the IPv4 networks (e.g. "10.0.0.0/16") attached to an
// interface; it may be nil.
func Expand(cfg model.Config, ifaceNets func(iface string) []string) Desired {
	var d Desired
	for _, a := range cfg.Addresses {
		if !a.Disabled {
			d.Addresses = append(d.Addresses, a)
		}
	}
	for _, r := range cfg.Routes {
		if !r.Disabled {
			d.Routes = append(d.Routes, r)
		}
	}
	for _, r := range cfg.Rules {
		if !r.Disabled {
			d.Rules = append(d.Rules, r)
		}
	}
	d.Firewall.Policy = cfg.Firewall.Policy
	for _, r := range cfg.Firewall.Rules {
		if !r.Disabled {
			d.Firewall.Rules = append(d.Firewall.Rules, r)
		}
	}

	cr := cfg.ClientRouting
	if !cr.Enabled {
		return d
	}
	if cr.PriorityBase == 0 {
		cr.PriorityBase = defaultPriorityBase
	}
	tables := map[string]int{}
	for _, e := range cr.Exits {
		tables[e.Interface] = e.Table
	}

	seen := map[string]bool{}
	once := func(key string) bool {
		if seen[key] {
			return false
		}
		seen[key] = true
		return true
	}
	var genFW []model.FWRule
	n := 0
	for _, c := range cr.Clients {
		if c.Disabled {
			continue
		}
		t, ok := tables[c.Out]
		if !ok {
			continue
		}
		table := fmt.Sprint(t)
		src := "client:" + c.ID
		if once("default|" + c.Out) {
			d.Routes = append(d.Routes, model.Route{ID: "gen-" + src + "-default", Dst: "default", Dev: c.Out, Table: table,
				Comment: "client routing exit " + c.Out, Source: "client-routing"})
		}
		if once("back|" + c.In + "|" + c.Out) {
			var nets []string
			if ifaceNets != nil {
				nets = ifaceNets(c.In)
			}
			sort.Strings(nets)
			for _, net := range nets {
				d.Routes = append(d.Routes, model.Route{ID: "gen-" + src + "-back-" + net, Dst: net, Dev: c.In, Table: table,
					Comment: "return path to " + c.In, Source: "client-routing"})
			}
		}
		d.Rules = append(d.Rules, model.Rule{ID: "gen-" + src, Priority: cr.PriorityBase + 2*n, Src: c.Src, Action: "lookup", Table: table,
			Comment: nameOr(c, "client") + " via " + c.Out, Source: "client-routing"})
		if c.KillSwitch {
			d.Rules = append(d.Rules, model.Rule{ID: "gen-" + src + "-kill", Priority: cr.PriorityBase + 2*n + 1, Src: c.Src, Action: "blackhole",
				Comment: "kill switch for " + nameOr(c, "client"), Source: "client-routing"})
		}
		n++
		if once("masq|" + c.Out) {
			genFW = append(genFW, model.FWRule{ID: "gen-masq-" + c.Out, Chain: model.ChainPostrouting, Action: "masquerade", OutIface: c.Out,
				Comment: "client routing", Source: "client-routing"})
		}
		if once("fwd|" + c.In + "|" + c.Out) {
			genFW = append(genFW, model.FWRule{ID: "gen-fwd-" + c.In + "-" + c.Out, Chain: model.ChainForward, Action: "accept", InIface: c.In, OutIface: c.Out,
				Comment: "client routing", Source: "client-routing"})
		}
	}
	if len(genFW) > 0 {
		// Replies to forwarded traffic must pass even under a drop policy.
		est := model.FWRule{ID: "gen-fwd-established", Chain: model.ChainForward, Action: "accept", ConnState: "established,related",
			Comment: "client routing", Source: "client-routing"}
		d.Firewall.Rules = append(append([]model.FWRule{est}, genFW...), d.Firewall.Rules...)
	}
	return d
}

func nameOr(c model.ClientRoute, def string) string {
	if c.Name != "" {
		return c.Name
	}
	return def + " " + c.Src
}

// NetsOf turns "10.0.0.1/16" style addresses into their network prefixes.
func NetsOf(addrs []string) []string {
	var out []string
	for _, a := range addrs {
		if _, n, err := net.ParseCIDR(a); err == nil {
			ones, _ := n.Mask.Size()
			if ones < 32 {
				out = append(out, n.String())
			}
		}
	}
	return out
}
