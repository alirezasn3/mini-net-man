// NewID returns a short random id for a config item.
func NewID() string {
	b := make([]byte, 4)
	_, _ = rand.Read(b)
	return hex.EncodeToString(b)
}

// Desired is everything the kernel should look like, after the optional
// client-routing feature has been expanded into plain items.
type Desired struct {
	Bridges    []model.Bridge
	Interfaces []model.LinkSetting
	Addresses  []model.Address
	Routes     []model.Route
	Rules      []model.Rule
	Firewall   model.Firewall
}

const (
	defaultTableBase    = 200
	defaultPriorityBase = 10000
)

// AllocateExits makes sure every output interface used by an enabled client
// has a stable routing table in cfg.ClientRouting.Exits.
func AllocateExits(cfg *model.Config) {
	cr := &cfg.ClientRouting
	if cr.TableBase == 0 {
		cr.TableBase = defaultTableBase
	}
	if cr.PriorityBase == 0 {
		cr.PriorityBase = defaultPriorityBase
	}
	used := map[int]bool{}
	have := map[string]bool{}
	for _, e := range cr.Exits {
		used[e.Table] = true
		have[e.Interface] = true
	}
	for _, c := range cr.Clients {
		if have[c.Out] {
			continue
		}
		t := cr.TableBase
		for used[t] || t == model.TableDefault || t == model.TableMain || t == model.TableLocal {
			t++
		}
		used[t], have[c.Out] = true, true
		cr.Exits = append(cr.Exits, model.Exit{Interface: c.Out, Table: t})
	}
}

// Expand merges manual items with the ones generated by client routing.
// ifaceNets returns the IPv4 networks (e.g. "10.0.0.0/16") attached to an
// interface; it may be nil.
//
// down reports whether a health check is failing (nil means none are); rules
// that depend on a failing check are left out, which removes them from the
// kernel until the check recovers.
func Expand(cfg model.Config, ifaceNets func(iface string) []string, down func(checkID string) bool) Desired {
	var d Desired
	for _, b := range cfg.Bridges {
		if !b.Disabled {
			d.Bridges = append(d.Bridges, b)
		}
	}
	for _, l := range cfg.Interfaces {
		if !l.Disabled {
			d.Interfaces = append(d.Interfaces, l)
		}
	}
	for _, a := range cfg.Addresses {
		if !a.Disabled {
			d.Addresses = append(d.Addresses, a)
		}
	}
	for _, r := range cfg.Routes {
		if !r.Disabled {
			d.Routes = append(d.Routes, r)
		}
	}
	for _, r := range cfg.Rules {
		if r.Disabled || (r.Check != "" && down != nil && down(r.Check)) {
			continue
		}
		d.Rules = append(d.Rules, r)
	}
	d.Rules = append(d.Rules, checkRoutes(cfg.Checks)...)
	d.Firewall.Policy = cfg.Firewall.Policy
	for _, r := range cfg.Firewall.Rules {
		if !r.Disabled {
			d.Firewall.Rules = append(d.Firewall.Rules, r)
		}
	}

	cr := cfg.ClientRouting
	if !cr.Enabled {
		return d
	}
	if cr.PriorityBase == 0 {
		cr.PriorityBase = defaultPriorityBase
	}
	tables := map[string]int{}
	for _, e := range cr.Exits {
		tables[e.Interface] = e.Table
	}

	seen := map[string]bool{}
	once := func(key string) bool {
		if seen[key] {
			return false
		}
		seen[key] = true
		return true
	}
	var genFW []model.FWRule
	n := 0
	for _, c := range cr.Clients {
		if c.Disabled {
			continue
		}
		t, ok := tables[c.Out]
		if !ok {
			continue
		}
		table := fmt.Sprint(t)
		src := "client:" + c.ID
		// A client is IPv4 or IPv6 depending on its address. Each family has
		// its own routes inside the exit's table (table numbers are per family).
		fam, def := "ipv4", "default"
		if v6, _ := clientIsV6(c.Src); v6 {
			fam, def = "ipv6", "::/0"
		}
		if once("default|" + c.Out + "|" + fam) {
			d.Routes = append(d.Routes, model.Route{ID: "gen-" + src + "-default", Dst: def, Dev: c.Out, Table: table,
				Comment: "client routing exit " + c.Out, Source: "client-routing"})
		}
		if once("back|" + c.In + "|" + c.Out + "|" + fam) {
			var nets []string
			if ifaceNets != nil {
				nets = ifaceNets(c.In)
			}
			sort.Strings(nets)
			for _, nt := range nets {
				if v6, err := clientIsV6(nt); err != nil || v6 != (fam == "ipv6") {
					continue
				}
				d.Routes = append(d.Routes, model.Route{ID: "gen-" + src + "-back-" + nt, Dst: nt, Dev: c.In, Table: table,
					Comment: "return path to " + c.In, Source: "client-routing"})
			}
		}
		d.Rules = append(d.Rules, model.Rule{ID: "gen-" + src, Priority: cr.PriorityBase + 2*n, Src: c.Src, Action: "lookup", Table: table,
			Comment: nameOr(c, "client") + " via " + c.Out, Source: "client-routing"})
		if c.KillSwitch {
			d.Rules = append(d.Rules, model.Rule{ID: "gen-" + src + "-kill", Priority: cr.PriorityBase + 2*n + 1, Src: c.Src, Action: "blackhole",
				Comment: "kill switch for " + nameOr(c, "client"), Source: "client-routing"})
		}
		n++
		if once("masq|" + c.Out + "|" + fam) {
			genFW = append(genFW, model.FWRule{ID: "gen-masq-" + c.Out + "-" + fam, Chain: model.ChainPostrouting, Action: "masquerade", OutIface: c.Out,
				Family: fam, Comment: "client routing", Source: "client-routing"})
		}
		if once("fwd|" + c.In + "|" + c.Out) {
			genFW = append(genFW, model.FWRule{ID: "gen-fwd-" + c.In + "-" + c.Out, Chain: model.ChainForward, Action: "accept", InIface: c.In, OutIface: c.Out,
				Comment: "client routing", Source: "client-routing"})
		}
	}
	if len(genFW) > 0 {
		// Replies to forwarded traffic must pass even under a drop policy.
		est := model.FWRule{ID: "gen-fwd-established", Chain: model.ChainForward, Action: "accept", ConnState: "established,related",
			Comment: "client routing", Source: "client-routing"}
		d.Firewall.Rules = append(append([]model.FWRule{est}, genFW...), d.Firewall.Rules...)
	}
	return d
}

func clientIsV6(s string) (bool, error) {
	n, err := model.ParseCIDR(s, false)
	if err != nil {
		return false, err
	}
	return model.IsV6(n), nil
}

func nameOr(c model.ClientRoute, def string) string {
	if c.Name != "" {
		return c.Name
	}
	return def + " " + c.Src
}

// NetsOf turns "10.0.0.1/16" or "fd00::1/64" style interface addresses into
// network prefixes, skipping host addresses (/32, /128) and IPv6 link-local.
func NetsOf(addrs []string) []string {
	var out []string
	for _, a := range addrs {
		ip, n, err := net.ParseCIDR(a)
		if err != nil {
			continue
		}
		ones, bits := n.Mask.Size()
		if ones == bits || (ip.To4() == nil && ip.IsLinkLocalUnicast()) {
			continue
		}
		out = append(out, n.String())
	}
	return out
}

// checkHelperPriority puts the helper rules right after the system's own
// "local" rule, so nothing else gets a say first.
const checkHelperPriority = 1

// checkRoutes lets a health check use the route of the exit it watches. A ping
// bound to an interface only considers routes through that interface; with no
// route found Linux assumes the target is directly on the link, which is right
// for a tunnel but wrong for an exit reached through a gateway whose route
// lives in a custom table. A check that names a table gets the rule
// `oif <interface> lookup <table>`. It matches only packets sent from a socket
// bound to that interface, which is to say the check's own pings, and affects
// nothing else.
func checkRoutes(checks []model.Check) []model.Rule {
	var out []model.Rule
	seen := map[string]bool{}
	for _, c := range checks {
		if c.Table == "" {
			continue
		}
		fam := "ipv4"
		if c.V6() {
			fam = "ipv6"
		}
		key := c.Interface + "|" + c.Table + "|" + fam
		if seen[key] {
			continue
		}
		seen[key] = true
		out = append(out, model.Rule{ID: "gen-check-" + c.ID, Priority: checkHelperPriority, Oif: c.Interface, Family: fam,
			Action: "lookup", Table: c.Table, Comment: "route for health check " + c.Name, Source: "health check"})
	}
	return out
}
