// Package dnsmasq turns the DHCP and DNS settings into a dnsmasq config file
// and reads back its leases. Running the program is the supervisor's job
// (package svc).
package dnsmasq

import (
	"bufio"
	"context"
	"errors"
	"fmt"
	"net/netip"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
	"time"

	"github.com/alirezasn3/mini-net-man/internal/distro"
	"github.com/alirezasn3/mini-net-man/internal/model"
)

// Input is everything the config file is made from.
type Input struct {
	Settings model.DNSMasq
	Scopes   []model.DHCPScope
	Hosts    []model.DHCPHost
	Records  []model.DNSRecord
	Dir      string // where dnsmasq keeps its lease file and pid file
}

// Enabled reports whether there is anything for dnsmasq to do.
func (in Input) Enabled() bool {
	return in.Settings.Enabled && (len(in.scopes()) > 0 || in.ServesDNS())
}

// ServesDNS reports whether dnsmasq answers DNS queries at all.
func (in Input) ServesDNS() bool {
	return in.Settings.DNS && len(in.Interfaces()) > 0
}

func (in Input) scopes() []model.DHCPScope {
	var out []model.DHCPScope
	for _, s := range in.Scopes {
		if !s.Disabled {
			out = append(out, s)
		}
	}
	return out
}

// Interfaces are the interfaces dnsmasq listens on: those of the DHCP scopes,
// plus the extra ones for DNS.
func (in Input) Interfaces() []string {
	seen := map[string]bool{}
	var out []string
	for _, s := range in.scopes() {
		if !seen[s.Interface] {
			seen[s.Interface] = true
			out = append(out, s.Interface)
		}
	}
	for _, i := range in.Settings.Interfaces {
		if !seen[i] {
			seen[i] = true
			out = append(out, i)
		}
	}
	sort.Strings(out)
	return out
}

// ConfPath, LeasePath and PIDPath are where the files live.
func ConfPath(dir string) string  { return filepath.Join(dir, "dnsmasq.conf") }
func LeasePath(dir string) string { return filepath.Join(dir, "dnsmasq.leases") }
func PIDPath(dir string) string   { return filepath.Join(dir, "dnsmasq.pid") }

// Tag is the dnsmasq tag a scope's options hang on.
func Tag(s model.DHCPScope) string { return "s_" + s.ID }

func leaseArg(t string) string {
	secs, _ := model.LeaseSeconds(t)
	switch {
	case secs < 0:
		return "infinite"
	case secs%3600 == 0:
		return strconv.Itoa(secs/3600) + "h"
	case secs%60 == 0:
		return strconv.Itoa(secs/60) + "m"
	}
	return strconv.Itoa(secs)
}

// Render writes the dnsmasq configuration. Every value in it was validated as
// a name, an address or a number, and free text (comments) is left out, so
// nothing a user types can add a line of its own.
func Render(in Input) string {
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format+"\n", a...) }
	w("# Generated by mini-net-man. Edit the settings in the panel: changes here are overwritten.")
	w("keep-in-foreground")
	w("log-facility=-") // to stderr, where mini-net-man collects it
	w("pid-file=%s", PIDPath(in.Dir))
	w("dhcp-leasefile=%s", LeasePath(in.Dir))
	w("bind-dynamic")
	w("domain-needed")
	w("bogus-priv")
	for _, i := range in.Interfaces() {
		w("interface=%s", i)
	}
	dnsOn := in.ServesDNS()
	if !dnsOn {
		w("port=0")
	} else {
		if ups := in.Settings.Upstreams; len(ups) > 0 {
			w("no-resolv")
			for _, u := range ups {
				w("server=%s", strings.TrimSpace(u))
			}
		}
		cache := in.Settings.CacheSize
		if cache == 0 {
			cache = 1000
		}
		w("cache-size=%d", cache)
		if d := strings.ToLower(in.Settings.Domain); d != "" {
			w("domain=%s", d)
			w("local=/%s/", d)
			w("expand-hosts")
		}
		for _, r := range in.Records {
			if r.Disabled {
				continue
			}
			name, target := strings.ToLower(strings.TrimSuffix(r.Name, ".")), strings.ToLower(strings.TrimSuffix(strings.TrimSpace(r.Address), "."))
			if r.IsAlias() {
				w("cname=%s,%s", name, target)
			} else {
				w("host-record=%s,%s", name, target)
			}
		}
	}
	scopes := in.scopes()
	if len(scopes) > 0 {
		w("dhcp-authoritative")
		if d := strings.ToLower(in.Settings.Domain); d != "" && !dnsOn {
			w("domain=%s", d)
		}
	}
	for _, s := range scopes {
		t := Tag(s)
		w("dhcp-range=tag:%s,set:%s,%s,%s,%s", s.Interface, t, strings.TrimSpace(s.Start), strings.TrimSpace(s.End), leaseArg(s.LeaseTime))
		switch r := strings.TrimSpace(s.Router); r {
		case "":
		case "none":
			w("dhcp-option=tag:%s,3", t)
		default:
			w("dhcp-option=tag:%s,3,%s", t, r)
		}
		switch {
		case len(s.DNS) > 0:
			ds := make([]string, len(s.DNS))
			for i, d := range s.DNS {
				ds[i] = strings.TrimSpace(d)
			}
			w("dhcp-option=tag:%s,6,%s", t, strings.Join(ds, ","))
		case !dnsOn:
			w("dhcp-option=tag:%s,6", t) // no DNS server to offer: send none
		}
		if d := strings.ToLower(s.Domain); d != "" {
			w("dhcp-option=tag:%s,15,%s", t, d)
		}
	}
	for _, h := range in.Hosts {
		if h.Disabled {
			continue
		}
		mac, _ := model.NormalizeMAC(h.MAC)
		line := fmt.Sprintf("dhcp-host=%s,%s", mac, strings.TrimSpace(h.IP))
		if h.Hostname != "" {
			line += "," + strings.ToLower(h.Hostname)
		}
		w("%s", line)
	}
	return b.String()
}

// Lease is one address dnsmasq has given out.
type Lease struct {
	Expires  int64  `json:"expires"` // unix time; 0 means never
	MAC      string `json:"mac"`
	IP       string `json:"ip"`
	Hostname string `json:"hostname"`
	ClientID string `json:"client_id,omitempty"`
}

// Leases reads dnsmasq's lease file; a missing file means no leases yet.
func Leases(path string) ([]Lease, error) {
	f, err := os.Open(path)
	if err != nil {
		if os.IsNotExist(err) {
			return []Lease{}, nil
		}
		return nil, err
	}
	defer f.Close()
	out := []Lease{}
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		fs := strings.Fields(sc.Text())
		if len(fs) < 4 || fs[0] == "duid" {
			continue
		}
		exp, err := strconv.ParseInt(fs[0], 10, 64)
		if err != nil {
			continue
		}
		mac, err := model.NormalizeMAC(fs[1])
		if err != nil {
			continue
		}
		if _, err := netip.ParseAddr(fs[2]); err != nil {
			continue
		}
		l := Lease{Expires: exp, MAC: mac, IP: fs[2]}
		if fs[3] != "*" {
			l.Hostname = fs[3]
		}
		if len(fs) > 4 && fs[4] != "*" {
			l.ClientID = fs[4]
		}
		out = append(out, l)
	}
	sort.Slice(out, func(i, j int) bool {
		a, _ := netip.ParseAddr(out[i].IP)
		b, _ := netip.ParseAddr(out[j].IP)
		return a.Compare(b) < 0
	})
	return out, sc.Err()
}

// Find returns the dnsmasq binary, or an error saying how to get one.
func Find() (string, error) {
	p, err := exec.LookPath("dnsmasq")
	if err != nil {
		msg := "dnsmasq is not installed"
		if c := distro.Detect().InstallCmd("dnsmasq"); c != "" {
			msg += " (install it with: " + c + "; the system service is not needed)"
		}
		return "", errors.New(msg)
	}
	return p, nil
}

// Check asks dnsmasq to parse a config file without starting.
func Check(bin, conf string) error {
	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancel()
	out, err := exec.CommandContext(ctx, bin, "--test", "--conf-file="+conf).CombinedOutput()
	if err != nil {
		msg := strings.TrimSpace(string(out))
		if msg == "" {
			msg = err.Error()
		}
		return fmt.Errorf("dnsmasq rejects the config: %s", msg)
	}
	return nil
}

// Version returns "2.90" style text, or "" when it can't be told.
func Version(bin string) string {
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
	defer cancel()
	out, err := exec.CommandContext(ctx, bin, "--version").Output()
	if err != nil {
		return ""
	}
	line, _, _ := strings.Cut(string(out), "\n")
	f := strings.Fields(line)
	if len(f) >= 3 && f[1] == "version" {
		return f[2]
	}
	return strings.TrimSpace(line)
}
