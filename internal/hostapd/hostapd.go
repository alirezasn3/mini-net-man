// Package hostapd writes the hostapd config for an access point and talks to a
// running hostapd over its control socket (to list the connected devices and
// disconnect one). Running the program is the supervisor's job (package svc).
package hostapd

import (
	"fmt"
	"net"
	"os"
	"os/exec"
	"path/filepath"
	"strconv"
	"strings"
	"sync/atomic"
	"time"

	"github.com/alirezasn3/mini-net-man/internal/model"
)

// ConfPath is the config file of the access point on iface.
func ConfPath(dir, iface string) string { return filepath.Join(dir, "hostapd-"+iface+".conf") }

// CtrlDir is the directory of hostapd's control sockets (one per interface).
func CtrlDir(dir string) string { return filepath.Join(dir, "hostapd-ctrl") }

// Name is the supervisor's name for this access point's process.
func Name(iface string) string { return "hostapd-" + iface }

// Render writes the hostapd configuration. Every value was validated (names,
// numbers, an ASCII password), none can contain a line break.
func Render(ap model.AccessPoint, dir string) string {
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format+"\n", a...) }
	w("# Generated by mini-net-man. Edit the access point in the panel: changes here are overwritten.")
	w("interface=%s", ap.Interface)
	w("driver=nl80211")
	w("ctrl_interface=%s", CtrlDir(dir))
	w("ctrl_interface_group=0")
	w("ssid=%s", ap.SSID)
	w("utf8_ssid=1")
	if ap.Country != "" {
		w("country_code=%s", ap.Country)
		w("ieee80211d=1")
		if ap.Band == "5" {
			w("ieee80211h=1") // needed on the channels that share spectrum with radar
		}
	}
	if ap.Band == "5" {
		w("hw_mode=a")
	} else {
		w("hw_mode=g")
	}
	w("channel=%d", ap.Channel) // 0 asks the driver to choose
	w("wmm_enabled=1")
	if ap.N || ap.AC || ap.AX {
		w("ieee80211n=1")
	}
	if ap.AC && ap.Band == "5" {
		w("ieee80211ac=1")
	}
	if ap.AX {
		w("ieee80211ax=1")
	}
	if ap.Hidden {
		w("ignore_broadcast_ssid=1")
	}
	if ap.Isolate {
		w("ap_isolate=1")
	}
	if ap.MaxClients > 0 {
		w("max_num_sta=%d", ap.MaxClients)
	}
	if ap.Bridge != "" {
		w("bridge=%s", ap.Bridge)
	}
	w("auth_algs=1")
	if ap.Security != "open" {
		w("wpa=2")
		w("rsn_pairwise=CCMP")
		switch ap.Security {
		case "wpa2":
			w("wpa_key_mgmt=WPA-PSK")
		case "wpa3":
			w("wpa_key_mgmt=SAE")
			w("ieee80211w=2")
			w("sae_require_mfp=1")
		case "wpa2+wpa3":
			w("wpa_key_mgmt=WPA-PSK SAE")
			w("ieee80211w=1") // protected management frames where the device supports them
			w("sae_require_mfp=1")
		}
		if len(ap.Passphrase) == 64 { // a raw key, valid only for WPA2
			w("wpa_psk=%s", strings.ToLower(ap.Passphrase))
		} else {
			w("wpa_passphrase=%s", ap.Passphrase)
		}
	}
	return b.String()
}

// Find returns the hostapd binary, or an error saying how to get one.
func Find() (string, error) {
	p, err := exec.LookPath("hostapd")
	if err != nil {
		return "", fmt.Errorf("hostapd is not installed (for example: apt install hostapd)")
	}
	return p, nil
}

// Station is a device connected to the access point.
type Station struct {
	MAC           string `json:"mac"`
	Flags         string `json:"flags,omitempty"`
	Signal        int    `json:"signal,omitempty"` // dBm; 0 when the driver doesn't say
	ConnectedSecs int    `json:"connected_secs"`
	InactiveMs    int    `json:"inactive_ms"`
	RxBytes       uint64 `json:"rx_bytes"`
	TxBytes       uint64 `json:"tx_bytes"`
	RxPackets     uint64 `json:"rx_packets"`
	TxPackets     uint64 `json:"tx_packets"`
}

// Status is what hostapd reports about its interface.
type Status struct {
	State   string `json:"state"` // ENABLED, DISABLED, ACS, DFS, COUNTRY_UPDATE, HT_SCAN...
	Channel int    `json:"channel"`
	Freq    int    `json:"freq"`
	Clients int    `json:"clients"`
}

var seq atomic.Uint64

// Control talks to hostapd's control socket.
type Control struct {
	Dir     string        // the control directory (CtrlDir)
	Timeout time.Duration // default 2 s
}

func (c Control) exchange(iface, cmd string) (string, error) {
	to := c.Timeout
	if to == 0 {
		to = 2 * time.Second
	}
	local := filepath.Join(os.TempDir(), fmt.Sprintf("mnm-hostapd-%d-%d", os.Getpid(), seq.Add(1)))
	conn, err := net.DialUnix("unixgram", &net.UnixAddr{Name: local, Net: "unixgram"}, &net.UnixAddr{Name: filepath.Join(c.Dir, iface), Net: "unixgram"})
	if err != nil {
		return "", fmt.Errorf("hostapd on %s is not answering: %w", iface, err)
	}
	defer os.Remove(local)
	defer conn.Close()
	_ = conn.SetDeadline(time.Now().Add(to))
	if _, err := conn.Write([]byte(cmd)); err != nil {
		return "", err
	}
	buf := make([]byte, 8192)
	n, err := conn.Read(buf)
	if err != nil {
		return "", fmt.Errorf("hostapd on %s did not answer %s: %w", iface, strings.Fields(cmd)[0], err)
	}
	return string(buf[:n]), nil
}

func kv(s string) map[string]string {
	m := map[string]string{}
	for _, l := range strings.Split(s, "\n") {
		if k, v, ok := strings.Cut(strings.TrimSpace(l), "="); ok {
			m[k] = v
		}
	}
	return m
}

func atoi(s string) int { n, _ := strconv.Atoi(s); return n }

// Status asks for the interface's state.
func (c Control) Status(iface string) (Status, error) {
	out, err := c.exchange(iface, "STATUS")
	if err != nil {
		return Status{}, err
	}
	m := kv(out)
	st := Status{State: m["state"], Channel: atoi(m["channel"]), Freq: atoi(m["freq"])}
	for k, v := range m {
		if strings.HasPrefix(k, "num_sta[") {
			st.Clients += atoi(v)
		}
	}
	return st, nil
}

func parseStation(out string) (Station, bool) {
	out = strings.TrimSpace(out)
	if out == "" || out == "FAIL" {
		return Station{}, false
	}
	first, rest, _ := strings.Cut(out, "\n")
	mac, err := model.NormalizeMAC(first)
	if err != nil {
		return Station{}, false
	}
	m := kv(rest)
	st := Station{MAC: mac, Flags: m["flags"], Signal: atoi(m["signal"]), ConnectedSecs: atoi(m["connected_time"]), InactiveMs: atoi(m["inactive_msec"])}
	u := func(k string) uint64 { n, _ := strconv.ParseUint(m[k], 10, 64); return n }
	st.RxBytes, st.TxBytes, st.RxPackets, st.TxPackets = u("rx_bytes"), u("tx_bytes"), u("rx_packets"), u("tx_packets")
	return st, true
}

// Stations lists the connected devices.
func (c Control) Stations(iface string) ([]Station, error) {
	out := []Station{}
	cmd := "STA-FIRST"
	for i := 0; i < 2100; i++ {
		resp, err := c.exchange(iface, cmd)
		if err != nil {
			return nil, err
		}
		st, ok := parseStation(resp)
		if !ok {
			break
		}
		out = append(out, st)
		cmd = "STA-NEXT " + st.MAC
	}
	return out, nil
}

// Kick disconnects a device. It may reconnect at once: this is not a ban.
func (c Control) Kick(iface, mac string) error {
	m, err := model.NormalizeMAC(mac)
	if err != nil {
		return err
	}
	out, err := c.exchange(iface, "DEAUTHENTICATE "+m)
	if err != nil {
		return err
	}
	if strings.TrimSpace(out) != "OK" {
		return fmt.Errorf("hostapd: %s", strings.TrimSpace(out))
	}
	return nil
}
